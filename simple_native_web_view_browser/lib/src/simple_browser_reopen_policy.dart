/// Действие при повторном открытии браузера, когда сессия уже активна.
enum SimpleBrowserReopenPolicy {
  /// Новый запрос отбрасывается: сессия и её обработчики сохраняются.
  discard,

  /// Сессия заменяется: привязываются только обработчики нового запроса,
  /// страница и настройки остаются прежними.
  replaceCallbacks,

  /// Сессия заменяется: привязываются обработчики нового запроса
  /// и применяются его настройки без перезагрузки страницы.
  replaceCallbacksAndSettings,

  /// Сессия заменяется полностью: обработчики, настройки, страница
  /// перезагружается на новый адрес. Значение по умолчанию.
  replaceCallbacksAndSettingsAndReload,
}
